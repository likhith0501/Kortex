import json
import uuid
from typing import Dict, Any, List
from pathlib import Path
import fitz  # PyMuPDF
from backend.config import REPORTS_DIR
from backend.database import get_connection
from backend.services.comparison_service import generate_comparison_matrix
from backend.services.gap_service import get_session_gaps

def generate_session_report(session_id: str, title: str = "Research Intelligence Synthesis Report", format_type: str = "markdown") -> Dict[str, Any]:
    conn = get_connection()
    cursor = conn.cursor()
    
    cursor.execute("SELECT * FROM sessions WHERE id = ?", (session_id,))
    session = cursor.fetchone()
    session_name = session["name"] if session else "Research Session"
    
    cursor.execute(
        """
        SELECT p.id, p.title, p.authors, p.year, p.abstract,
               a.summary, a.problem, a.method, a.dataset, a.metrics, a.results, a.contributions, a.limitations, a.future_work, a.source_label, a.evidence_json
        FROM papers p
        LEFT JOIN analyses a ON p.id = a.paper_id
        WHERE p.session_id = ?
        """,
        (session_id,)
    )
    papers = cursor.fetchall()
    conn.close()
    
    gaps = get_session_gaps(session_id)
    paper_ids = [p["id"] for p in papers]
    comparison = generate_comparison_matrix(session_id, paper_ids) if len(paper_ids) >= 2 else None

    # Generate Markdown Content
    md_lines = [
        f"# {title}",
        f"**Session:** {session_name}  ",
        f"**Papers Analyzed:** {len(papers)}  ",
        f"**Generated By:** Kortex Autonomous Research Intelligence  ",
        f"**Date:** {papers[0]['year'] if papers else '2024'} Research Synthesis Cycle  ",
        "\n---\n",
        "## 1. Executive Summary",
        f"This synthesis report consolidates empirical findings, methodological architectures, and open research challenges across {len(papers)} research papers in the active workspace. Every finding is grounded with exact page citations from the original literature.",
        "\n## 2. Analyzed Papers"
    ]
    
    for idx, p in enumerate(papers, 1):
        md_lines.append(f"\n### 2.{idx} {p['title']}")
        md_lines.append(f"*Authors:* {p['authors']} | *Year:* {p['year']} | *Source:* `{p['source_label'] or 'Extractive (no LLM)'}`")
        md_lines.append(f"\n**Core Problem:**\n{p['problem'] or 'N/A'}")
        md_lines.append(f"\n**Methodology & Architecture:**\n{p['method'] or 'N/A'}")
        md_lines.append(f"\n**Datasets & Benchmarks:**\n{p['dataset'] or 'N/A'}")
        md_lines.append(f"\n**Empirical Results:**\n{p['results'] or 'N/A'}")
        md_lines.append(f"\n**Limitations & Constraints:**\n{p['limitations'] or 'N/A'}")
        
    if comparison and comparison.get("matrix"):
        md_lines.append("\n## 3. Comparative Methodology Matrix")
        headers = ["Criterion"] + [p["title"][:25] + "..." for p in comparison["papers"]]
        md_lines.append("| " + " | ".join(headers) + " |")
        md_lines.append("| " + " | ".join(["---"] * len(headers)) + " |")
        for row in comparison["matrix"]:
            vals = [row["criterion"]]
            for p in comparison["papers"]:
                val_text = row["values"].get(p["id"], {}).get("text", "N/A")
                clean_text = val_text[:120].replace("\n", " ") + ("..." if len(val_text) > 120 else "")
                vals.append(clean_text)
            md_lines.append("| " + " | ".join(vals) + " |")

    if gaps:
        md_lines.append("\n## 4. Evidence-Backed Research Gaps & Open Challenges")
        for idx, g in enumerate(gaps, 1):
            md_lines.append(f"\n#### 4.{idx} {g['title']}")
            md_lines.append(f"- **Confidence:** {g['confidence']} ({g['rationale']})")
            md_lines.append(f"- **Category:** {g['category']} | **Frequency:** {g['frequency']} paper(s)")
            md_lines.append(f"- **Synthesis:** {g['text']}")
            if g.get("evidence"):
                md_lines.append("- **Supporting Evidence:**")
                for ev in g["evidence"][:3]:
                    md_lines.append(f"  - *{ev['paper_title']}* (p. {ev['page']}): \"{ev['excerpt'][:220]}...\"")

    report_content = "\n".join(md_lines)
    report_id = f"report_{uuid.uuid4().hex[:8]}"
    
    if format_type.lower() == "pdf":
        file_path = REPORTS_DIR / f"{report_id}.pdf"
        generate_pdf_from_text(title, report_content, file_path)
        filename = f"{report_id}.pdf"
    else:
        file_path = REPORTS_DIR / f"{report_id}.md"
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(report_content)
        filename = f"{report_id}.md"

    return {
        "report_id": report_id,
        "title": title,
        "filename": filename,
        "format": format_type,
        "content": report_content,
        "download_url": f"/api/reports/{filename}/download"
    }

def generate_pdf_from_text(title: str, text: str, output_path: Path):
    """Generates a clean, readable PDF report using PyMuPDF."""
    doc = fitz.open()
    
    # 72 points per inch, standard A4 is 595 x 842
    page = doc.new_page(width=595, height=842)
    margin = 50
    width = 595 - (2 * margin)
    
    # Colors
    primary_color = (0.04, 0.06, 0.12) # dark navy
    accent_color = (0.23, 0.43, 0.92)  # blue
    text_color = (0.1, 0.1, 0.15)
    
    y = 60
    # Header
    page.insert_text((margin, y), "RESEARCHMATE INTELLIGENCE REPORT", fontsize=10, color=accent_color)
    y += 24
    page.insert_text((margin, y), title[:45], fontsize=18, color=primary_color)
    y += 20
    page.draw_line((margin, y), (595 - margin, y), color=accent_color, width=1.5)
    y += 25
    
    # Render body paragraphs
    lines = text.split("\n")
    for line in lines:
        if y > 780:
            page = doc.new_page(width=595, height=842)
            y = 50
            
        line_str = line.strip()
        if not line_str:
            y += 8
            continue
            
        if line_str.startswith("# "):
            continue # already in title
        elif line_str.startswith("## "):
            y += 12
            if y > 780:
                page = doc.new_page(width=595, height=842)
                y = 50
            page.insert_text((margin, y), line_str.replace("## ", ""), fontsize=13, color=accent_color)
            y += 18
        elif line_str.startswith("### "):
            y += 8
            page.insert_text((margin, y), line_str.replace("### ", "")[:70], fontsize=11, color=primary_color)
            y += 15
        elif line_str.startswith("#### "):
            y += 6
            page.insert_text((margin, y), line_str.replace("#### ", "")[:75], fontsize=10, color=primary_color)
            y += 14
        else:
            # Normal text wrapped in rect
            clean_line = line_str.replace("**", "").replace("*", "").replace("`", "")
            # Insert textbox with auto line wrap
            rect = fitz.Rect(margin, y, 595 - margin, y + 45)
            rc = page.insert_textbox(rect, clean_line, fontsize=9, color=text_color, lineheight=1.2)
            y += max(14, int(len(clean_line) / 80) * 12 + 12)

    doc.save(str(output_path))
    doc.close()
